#[test]
fn blake3_official_vectors() {
    for (len, expected) in BLAKE3_VECTORS {
        let input: Vec<u8> = (0..len).map(|i| (i % 251) as u8).collect();
        assert_eq!(
            hex_digest(DigestAlgorithm::Blake3, &input),
            expected,
            "{len} bytes"
        );
    }
}

/// The streaming reader path gives the same digests as the vectors.
#[test]
fn hash_reader_matches_the_vectors() {
    let input: Vec<u8> = (0..102_400).map(|i| (i % 251) as u8).collect();
    let out = hash_reader(&input[..], &AlgorithmSet::all()).unwrap();
    assert_eq!(out.bytes, 102_400);
    assert_eq!(
        out.digests.get(DigestAlgorithm::Blake3).unwrap().to_hex(),
        BLAKE3_VECTORS[34].1
    );
}
