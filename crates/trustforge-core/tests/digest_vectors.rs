//! Known-answer tests for every digest algorithm.
//!
//! SHA-2 vectors are the FIPS 180-4 examples (cross-checked with coreutils
//! and Python's `hashlib`). BLAKE3 vectors are the default-hash outputs of
//! the official `test_vectors/test_vectors.json` in the BLAKE3 repository
//! (CC0-1.0 or Apache-2.0).

// clippy.toml allows unwrap and expect only inside #[test] functions; the
// helpers in this test crate panic on setup failures on purpose.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use trustforge_core::digest::{AlgorithmSet, DigestAlgorithm, MultiHasher, hash_reader};

fn hex_digest(algorithm: DigestAlgorithm, data: &[u8]) -> String {
    let mut hasher = MultiHasher::new(&AlgorithmSet::new([algorithm]).unwrap());
    hasher.update(data);
    hasher.finalize().get(algorithm).unwrap().to_hex()
}

/// The FIPS multi-block messages: 14 overlapping runs of `width` letters,
/// "abcd" "bcde" … for 448 bits, "abcdefgh" "bcdefghi" … for 896 bits.
fn fips_message(width: u8) -> Vec<u8> {
    (0..14).flat_map(|i| b'a' + i..b'a' + i + width).collect()
}

#[test]
fn sha256_fips_180_4() {
    let cases: [(Vec<u8>, &str); 5] = [
        (
            b"".to_vec(),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
        ),
        (
            b"abc".to_vec(),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
        ),
        (
            fips_message(4),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1",
        ),
        (
            fips_message(8),
            "cf5b16a778af8380036ce59e7b0492370b249b11e8f07a51afac45037afee9d1",
        ),
        (
            vec![b'a'; 1_000_000],
            "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0",
        ),
    ];
    for (message, expected) in cases {
        assert_eq!(
            hex_digest(DigestAlgorithm::Sha256, &message),
            expected,
            "{} bytes",
            message.len()
        );
    }
}

